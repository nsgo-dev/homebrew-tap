#!/usr/bin/env ruby
# frozen_string_literal: true

# Writes Formula/nsgo.rb for one nsgo release from the release's checksums.txt; see README.md.
#
#   script/generate-formula.rb v0.3.4
#   script/generate-formula.rb --base-url file:///tmp/release --output /tmp/nsgo.rb v0.0.1
#
# Only Ruby's standard library, so it runs on any Ruby from 2.6 on.

require "fileutils"
require "open-uri"
require "optparse"

RELEASES = "https://github.com/nsgo-dev/nsgo/releases/download"

# The formula's blocks in order: on_macos/on_linux, on_arm/on_intel, and the archive's os and arch.
PLATFORMS = [
  %w[on_macos on_arm darwin arm64],
  %w[on_macos on_intel darwin amd64],
  %w[on_linux on_arm linux arm64],
  %w[on_linux on_intel linux amd64],
].freeze

def fail_with(message)
  warn "generate-formula: #{message}"
  exit 1
end

def read_source(source)
  if source.start_with?("https://", "http://", "file://")
    uri = URI.parse(source)
    return File.read(uri.path) if uri.scheme == "file"

    uri.open("rb", &:read)
  else
    File.read(source)
  end
rescue OpenURI::HTTPError, SystemCallError, SocketError => e
  fail_with "reading #{source}: #{e.message}"
end

# Parses sha256sum output ("<hex>  <file>", or "<hex> *<file>" in binary mode) into file name => checksum.
def parse_checksums(text, source)
  sums = {}
  text.each_line.with_index(1) do |line, number|
    line = line.chomp
    next if line.strip.empty?

    match = /\A([0-9a-f]{64}) [ *](\S+)\z/.match(line)
    fail_with "#{source}:#{number}: not a sha256sum line: #{line.inspect}" unless match
    sum, name = match.captures
    if sums.key?(name) && sums[name] != sum
      fail_with "#{source}:#{number}: #{name} is listed twice with different checksums"
    end
    sums[name] = sum
  end
  sums
end

def archive(version, os, arch)
  "nsgo_#{version}_#{os}_#{arch}.tar.gz"
end

def formula(version, base_url, sums)
  # Homebrew scans the version from a GitHub release URL and audit --strict refuses it twice, so only others state it.
  github_release = %r{\Ahttps://github\.com/[^/]+/[^/]+/releases/download/v#{Regexp.escape(version)}\z}
  version_line = base_url.match?(github_release) ? "" : "  version \"#{version}\"\n"
  blocks = PLATFORMS.group_by(&:first).map do |os_block, entries|
    arch_blocks = entries.map do |_, arch_block, os, arch|
      asset = archive(version, os, arch)
      <<-RUBY
    #{arch_block} do
      url "#{base_url}/#{asset}"
      sha256 "#{sums.fetch(asset)}"
    end
      RUBY
    end
    "  #{os_block} do\n#{arch_blocks.join("\n")}  end\n"
  end

  <<~RUBY
    # Generated by script/generate-formula.rb from the release's checksums.txt; edit the script instead.
    class Nsgo < Formula
      desc "Build, run and package native apps written in Go for every platform"
      homepage "https://nsgo.dev"
    #{version_line}  license "Apache-2.0"

      livecheck do
        url :stable
        strategy :github_latest
      end

    #{blocks.join("\n")}
      def install
        bin.install "nsgo"
      end

      test do
        assert_match "nsgo v\#{version}", shell_output("\#{bin}/nsgo version")
      end
    end
  RUBY
end

options = { output: File.expand_path("../Formula/nsgo.rb", __dir__) }
parser = OptionParser.new do |opts|
  opts.banner = "usage: script/generate-formula.rb [--base-url URL] [--checksums PATH|URL] [--output FILE] vX.Y.Z"
  opts.on("--base-url URL", "the directory holding the release's assets (default: #{RELEASES}/<tag>)") do |url|
    options[:base_url] = url.chomp("/")
  end
  opts.on("--checksums SOURCE", "where to read checksums.txt (default: <base-url>/checksums.txt)") do |source|
    options[:checksums] = source
  end
  opts.on("--output FILE", "the formula to write (default: Formula/nsgo.rb)") do |file|
    options[:output] = file
  end
end
begin
  parser.parse!
rescue OptionParser::ParseError => e
  fail_with "#{e.message}\n#{parser.banner}"
end
fail_with parser.banner if ARGV.length != 1

tag = ARGV.first
match = /\Av(\d+\.\d+\.\d+)\z/.match(tag)
fail_with "#{tag.inspect} is not a release tag of the form vX.Y.Z" unless match
version = match[1]

base_url = options[:base_url] || "#{RELEASES}/#{tag}"
source = options[:checksums] || "#{base_url}/checksums.txt"
sums = parse_checksums(read_source(source), source)

missing = PLATFORMS.map { |_, _, os, arch| archive(version, os, arch) }.reject { |asset| sums.key?(asset) }
fail_with "#{source} lacks #{missing.join(", ")}; refusing a release without every archive" unless missing.empty?

output = options[:output]
FileUtils.mkdir_p(File.dirname(output))
File.write(output, formula(version, base_url, sums))
puts "#{output}: nsgo #{version}"
